<?php

namespace App\Traits;

use Illuminate\Support\Facades\Process;

/**
 * Backup inventory and off-site destination config.
 *
 * The inventory is deliberately a declared allow-list rather than "every PVC",
 * because the two are very different sizes and only one of them matters:
 * Prometheus alone is ~4x the size of everything irreplaceable put together,
 * and losing it costs you graphs, not business data.
 *
 * The destination is any S3-compatible endpoint (Backblaze B2, DigitalOcean
 * Spaces, AWS). It must NOT be the cluster's own SeaweedFS — that lives on the
 * same block device as everything it would be backing up, so a disk or droplet
 * loss takes the data and the backups together. See
 * docs/decisions/0010-backup-strategy.md.
 */
trait InteractsWithBackup
{
    use ReadsClusterSecrets;

    /** Where the destination config Secret lives. */
    protected function backupNamespace(): string
    {
        return 'larakube-shared';
    }

    protected function backupKubectl(?string $context = null): string
    {
        $context = (string) ($context ?? '');
        $kubectl = 'KUBECONFIG='.escapeshellarg(home_path('.kube/config')).' kubectl';

        return $context !== '' ? "{$kubectl} --context={$context}" : $kubectl;
    }

    /**
     * Volumes whose contents cannot be rebuilt from anything else.
     *
     * Each entry: the Deployment to exec into, its namespace, the container,
     * and the path to archive. Excluded on purpose:
     *   - prometheus-storage — metrics history, ~1.1G, rebuildable by waiting
     *   - chat-synapse's media_store and site-packages — media is mirrored to
     *     object storage and pip re-installs on every pod start; only the
     *     59-byte signing key matters, and it is captured below
     *   - webmail-storage — regenerated by webmail:init
     *
     * @return array<int, array{name: string, namespace: string, deployment: string, container: string, path: string}>
     */
    protected function backupVolumeTargets(): array
    {
        return [
            // The object store itself. Holds chat media, git LFS, notes, sheets,
            // signed documents and screen recordings — archived whole because
            // SeaweedFS stores volume files, not a browsable tree.
            ['name' => 'seaweedfs', 'namespace' => 'larakube-plex', 'deployment' => 'seaweedfs', 'container' => 'seaweedfs', 'path' => '/data'],
            ['name' => 'openbao', 'namespace' => 'larakube-secrets', 'deployment' => 'openbao-backend', 'container' => 'openbao', 'path' => '/openbao'],
            ['name' => 'forgejo', 'namespace' => 'larakube-shared', 'deployment' => 'forgejo', 'container' => 'forgejo', 'path' => '/data'],
            ['name' => 'drive-ocis', 'namespace' => 'larakube-shared', 'deployment' => 'drive-ocis', 'container' => 'ocis', 'path' => '/var/lib/ocis'],
            ['name' => 'vaultwarden', 'namespace' => 'larakube-vault', 'deployment' => 'vaultwarden', 'container' => 'vaultwarden', 'path' => '/data'],
            ['name' => 'stalwart', 'namespace' => 'larakube-shared', 'deployment' => 'stalwart', 'container' => 'stalwart', 'path' => '/var/lib/stalwart'],
            // Losing this 59-byte key means the homeserver can no longer prove
            // it is the same server: federation and every existing device
            // session break, permanently.
            ['name' => 'synapse-identity', 'namespace' => 'larakube-shared', 'deployment' => 'chat-synapse', 'container' => 'synapse', 'path' => '/data/chat.luchtech.dev.signing.key'],
        ];
    }

    /**
     * Every non-template database in the Commons Postgres. Read live rather
     * than hardcoded so a newly installed tool is covered without a code change
     * — the failure mode of a static list is a database silently not backed up.
     *
     * @return array<int, string>
     */
    protected function backupDatabases(string $kubectl, string $plexNamespace = 'larakube-plex'): array
    {
        $out = Process::timeout(60)->run(
            "{$kubectl} exec deploy/postgres -n {$plexNamespace} -c postgres -- "
            ."psql -U postgres -tAc \"select datname from pg_database where datistemplate = false and datname <> 'postgres'\"",
        )->output();

        return array_values(array_filter(array_map('trim', explode("\n", $out))));
    }

    /**
     * The off-site destination, or null when `backup:init` has not run.
     *
     * @return array{endpoint: string, bucket: string, access_key: string, secret_key: string, passphrase: string, region: string}|null
     */
    protected function readBackupConfig(string $kubectl, string $ns): ?array
    {
        $read = fn (string $key): ?string => $this->readClusterSecretKey($kubectl, $ns, 'larakube-backup-config', $key);

        $bucket = $read('bucket');

        if ($bucket === null || $bucket === '') {
            return null;
        }

        return [
            'endpoint' => $read('endpoint') ?? '',
            'bucket' => $bucket,
            'access_key' => $read('access-key') ?? '',
            'secret_key' => $read('secret-key') ?? '',
            'passphrase' => $read('passphrase') ?? '',
            'region' => $read('region') ?? 'us-east-1',
        ];
    }

    /**
     * Guard against the most seductive wrong answer: pointing backups at the
     * cluster's own SeaweedFS. It is on the same block device as every volume
     * it would be protecting, so it survives exactly the failures that do not
     * matter and none of the ones that do.
     */
    protected function backupDestinationIsOnCluster(string $endpoint): bool
    {
        return str_contains($endpoint, '.svc.cluster.local')
            || str_contains($endpoint, 'seaweedfs')
            || str_contains($endpoint, 'localhost')
            || str_contains($endpoint, '127.0.0.1');
    }
}
